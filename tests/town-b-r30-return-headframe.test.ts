import assert from 'node:assert/strict';
import test from 'node:test';
import {Raycaster,Vector3} from 'three';
import {createTerrainGrid,worldBounds} from '../tools/voxel-tavern/town-blockout/terrain';
import {mountWestCraterRoad} from '../tools/voxel-tavern/town-blockout/town-za22-crater-road';
import {buildCraterRailExtension} from '../tools/voxel-tavern/town-blockout/town-crater-rail-extension';
import {attachBR30PhysicalKit} from '../tools/voxel-tavern/town-blockout/town-b-r30-physical-kit';
import {buildBR30ReturnHeadframe,surveyBR30ReturnHeadframe} from '../tools/voxel-tavern/town-blockout/town-b-r30-return-headframe';
test('B sealed headframe aligns C relocated dock and preserves the actual closed surface and return walk',()=>{
 const grid=createTerrainGrid(),road=mountWestCraterRoad(worldBounds.depth,n=>grid.groundHeightAt(0,n));
 const kit=attachBR30PhysicalKit(road,buildCraterRailExtension(grid,road));
 const before=road.group.userData.colliders;
 const candidate=buildBR30ReturnHeadframe(road),q=candidate.survey;
 assert.equal(candidate.group.parent,null);
 assert.equal(q.productionReady,false);
 assert.equal(q.apertureSide,2.2);
 assert.ok(Math.abs(q.localX-(-12.87600600249972))<1e-8&&Math.abs(q.localZ-(-.90834479104372))<1e-8);
 assert.ok(Math.abs(q.dockHeight-(-89.35458276044781))<1e-8&&q.verticalSpan>65&&q.verticalSpan<66);
 assert.ok(q.roofSpan<.01&&q.roofSamples>1000);
 assert.ok(q.solidGap>2.35&&q.reservationGap>2.35);
 assert.ok(q.routeGap>.35&&candidate.candidateGap>.35&&q.grade<.10&&candidate.extent<2.35);
 assert.ok(candidate.parts>=100&&candidate.worldBoxes.length===13);
 road.group.updateMatrixWorld(true);
 const ground=road.group.getObjectByName('meteor-crater-walk-mesh')!;
 const ray=new Raycaster(new Vector3(q.axis.east,q.axis.height+1,-q.axis.north),new Vector3(0,-1,0),0,2);
 const g=ray.intersectObject(ground)[0];
 assert.ok(g&&Math.abs(g.point.y-q.axis.height)<.01,'actual B ground remains uncut');
 road.group.add(candidate.group);road.group.updateMatrixWorld(true);
 const covered=ray.intersectObject(candidate.group,true)[0];
 assert.ok(covered&&covered.point.y>q.axis.height+.1,'physical closed iron cover');
 assert.equal(road.group.userData.colliders,before,'review prefab never changes production collision');
 candidate.dispose();
 assert.equal(candidate.group.parent,null);
 assert.equal(road.group.userData.colliders,before);
 const blocked={min:[q.axis.east-.1,q.axis.height,-q.axis.north-.1],max:[q.axis.east+.1,q.axis.height+1,-q.axis.north+.1]};
 road.group.userData.colliders=[...before,blocked];
 assert.throws(()=>surveyBR30ReturnHeadframe(road),/reservation no longer clear/);
 road.group.userData.colliders=before;kit.dispose();
});
