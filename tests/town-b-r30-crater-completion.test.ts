import assert from 'node:assert/strict';
import test from 'node:test';
import {createTerrainGrid,worldBounds} from '../tools/voxel-tavern/town-blockout/terrain';
import {mountWestCraterRoad} from '../tools/voxel-tavern/town-blockout/town-za22-crater-road';
import {buildCraterRailExtension} from '../tools/voxel-tavern/town-blockout/town-crater-rail-extension';
import {stripBR30LegacyTerraceMesh} from '../tools/voxel-tavern/town-blockout/town-b-r30-retire-legacy-terraces';
import {settleBR30StorySupports} from '../tools/voxel-tavern/town-blockout/town-b-r30-settle-story-supports';
import {attachBR30CraterCompletion} from '../tools/voxel-tavern/town-blockout/town-b-r30-crater-completion';
test('complete B crater candidate mounts six leaves exactly once and rolls back a late obstruction',()=>{
 const grid=createTerrainGrid(),road=mountWestCraterRoad(worldBounds.depth,n=>grid.groundHeightAt(0,n));
 stripBR30LegacyTerraceMesh(road.group);settleBR30StorySupports(road.group,road.heightAt);
 const rail=buildCraterRailExtension(grid,road),tracks=[rail.samples,rail.narrowSamples],original=road.group.userData.colliders;
 const names=['b-r30-pit-workface','b-r30-crater-workstations','b-r30-melt-columns','b-r30-mound-planting','mound-old-work-flag','b-r30-east-historic-walkway','b-r30-rubbing-transfer'];
 const oldVisibility=road.midground.group.children.map(o=>o.visible);
 const ground=road.group.getObjectByName('meteor-crater-walk-mesh')!;
 ground.userData.bR30UnifiedRelief=false;
 assert.throws(()=>attachBR30CraterCompletion(road,rail,tracks,'review'),/unified R30 crater ground/);
 assert.equal(road.group.userData.colliders,original);
 ground.userData.bR30UnifiedRelief=true;
 assert.throws(()=>attachBR30CraterCompletion(road,rail,tracks,'host-candidate'),/rail tracks/);
 const originalRail=rail.group.userData.colliders;rail.group.userData.colliders=[...(originalRail??[]),{min:[-88,-9,-192],max:[-86,-5,-190]}];
 assert.throws(()=>attachBR30CraterCompletion(road,rail,tracks,'review'),/overlaps existing solid/);
 assert.equal(road.group.userData.colliders,original);assert.ok(names.every(n=>!road.group.getObjectByName(n)));
 assert.deepEqual(road.midground.group.children.map(o=>o.visible),oldVisibility);
 rail.group.userData.colliders=originalRail;
 const m=attachBR30CraterCompletion(road,rail,tracks,'review');
 assert.equal(m.productionReady,false);assert.ok(names.every(n=>road.group.getObjectByName(n)));
 assert.equal(m.kit.machines.sites.length,5);assert.equal(m.melt.sites.length,14);assert.equal(m.historic.support.length,42);assert.equal(m.paper.cellCount,28);
 assert.equal(m.returnSurvey.productionReady,false);
 assert.throws(()=>attachBR30CraterCompletion(road,rail,tracks,'review'),/already attached/);
 const unrelated={min:[0,0,0],max:[1,1,1]};road.group.userData.colliders.push(unrelated);
 m.dispose();m.dispose();assert.ok(names.every(n=>!road.group.getObjectByName(n)));assert.ok(original.every((b:unknown)=>road.group.userData.colliders.includes(b)));assert.ok(road.group.userData.colliders.includes(unrelated));
});
