import assert from 'node:assert/strict';
import test from 'node:test';
import {createTerrainGrid,worldBounds} from '../tools/voxel-tavern/town-blockout/terrain';
import {mountWestCraterRoad} from '../tools/voxel-tavern/town-blockout/town-za22-crater-road';
import {buildCraterRailExtension} from '../tools/voxel-tavern/town-blockout/town-crater-rail-extension';
import {attachBR30PhysicalKit} from '../tools/voxel-tavern/town-blockout/town-b-r30-physical-kit';
import {installBR30MoundPlanting} from '../tools/voxel-tavern/town-blockout/town-b-r30-mound-planting';
import {buildBR30ReturnHeadframe} from '../tools/voxel-tavern/town-blockout/town-b-r30-return-headframe';
test('mound replacement keeps canonical count, actual terrain support, single LOD host and protected return geometry',()=>{
 const grid=createTerrainGrid(),road=mountWestCraterRoad(worldBounds.depth,n=>grid.groundHeightAt(0,n));
 const kit=attachBR30PhysicalKit(road,buildCraterRailExtension(grid,road));
 const before=[...road.group.userData.colliders],old=road.moundPlanting.group.children.map(child=>({child,visible:child.visible}));
 const m=installBR30MoundPlanting(road);
 assert.equal(m.sites.filter(s=>s.ring==='slope').length,24);
 assert.equal(m.sites.filter(s=>s.ring==='summit').length,12);
 assert.equal(m.sites.filter(s=>s.ring==='flags').length,3);
 assert.ok(m.parts>400&&m.group.children.length<=10);
 assert.equal(m.group.parent,road.moundPlanting.group);
 assert.ok(old.every(p=>!p.child.visible));
 assert.ok(m.sites.every(s=>s.height===road.heightAt(s.east,s.north)));
 assert.equal(m.boxes.length,39);
 assert.equal(road.group.userData.colliders.length,before.length+39);
 assert.ok(m.audit.bodyGap>=.4&&m.audit.maxGrade<=.62);
 assert.throws(()=>installBR30MoundPlanting(road),/already mounted/);
 const headframe=buildBR30ReturnHeadframe(road);headframe.dispose();
 m.dispose();m.dispose();assert.deepEqual(road.group.userData.colliders,before);
 assert.ok(old.every(p=>p.child.visible===p.visible));
 kit.dispose();
});
